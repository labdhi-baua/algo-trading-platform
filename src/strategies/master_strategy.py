    def store_signal(self, signal: TradeSignal) -> bool:
        """Store signal in database"""
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()

        signal_dict = signal.to_dict()

        try:
            cursor.execute('''
                INSERT INTO signals 
                (ticker, timestamp, signal_type, confidence, entry_price, 
                 stop_loss, take_profit, risk_reward, reason, indicators, strategy)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            ''', (
                signal_dict['ticker'],
                signal_dict['timestamp'],
                signal_dict['signal_type'],
                signal_dict['confidence'],
                signal_dict['entry_price'],
                signal_dict['stop_loss'],
                signal_dict['take_profit'],
                signal_dict['risk_reward'],
                signal_dict['reason'],
                signal_dict['indicators'],
                signal_dict['strategy']
            ))

            conn.commit()
            logger.info(f"✓ Signal stored: {signal.ticker} {signal.signal_type}")
            conn.close()
            return True

        except sqlite3.IntegrityError as e:
            logger.warning(f"⚠ Signal already exists: {signal.ticker}")
            conn.close()
            return False
        except Exception as e:
            logger.error(f"✗ Error storing signal: {e}")
            conn.close()
            return False

    def get_recent_signals(self, limit: int = 20, signal_type: str = None) -> List[Dict]:
        """Get recent signals from database"""
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()

        if signal_type:
            cursor.execute('''
                SELECT * FROM signals 
                WHERE signal_type = ?
                ORDER BY timestamp DESC 
                LIMIT ?
            ''', (signal_type, limit))
        else:
            cursor.execute('''
                SELECT * FROM signals 
                ORDER BY timestamp DESC 
                LIMIT ?
            ''', (limit,))

        columns = [description[0] for description in cursor.description]
        signals = [dict(zip(columns, row)) for row in cursor.fetchall()]

        conn.close()
        return signals

    def get_signal_stats(self) -> Dict:
        """Get statistics on generated signals"""
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()

        cursor.execute('SELECT COUNT(*) FROM signals WHERE signal_type = "BUY"')
        buy_count = cursor.fetchone()[0]

        cursor.execute('SELECT COUNT(*) FROM signals WHERE signal_type = "SELL"')
        sell_count = cursor.fetchone()[0]

        cursor.execute('SELECT AVG(confidence) FROM signals WHERE signal_type = "BUY"')
        avg_buy_conf = cursor.fetchone()[0] or 0

        cursor.execute('SELECT AVG(confidence) FROM signals WHERE signal_type = "SELL"')
        avg_sell_conf = cursor.fetchone()[0] or 0

        conn.close()

        return {
            'total_buy_signals': buy_count,
            'total_sell_signals': sell_count,
            'avg_buy_confidence': round(avg_buy_conf, 2),
            'avg_sell_confidence': round(avg_sell_conf, 2),
            'total_signals': buy_count + sell_count
        }


