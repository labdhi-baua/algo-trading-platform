class TradeSignal:
    """
    Represents a trading signal generated by the strategy
    """

    def __init__(self,
                 ticker: str,
                 timestamp: datetime,
                 signal_type: str,  # BUY, SELL, HOLD
                 confidence: float,  # 0-100
                 entry_price: float,
                 stop_loss: float,
                 take_profit: float,
                 reason: str,
                 indicators_aligned: List[str],
                 strategy_used: str = "Master Strategy"):
        self.ticker = ticker
        self.timestamp = timestamp
        self.signal_type = signal_type  # BUY, SELL, HOLD
        self.confidence = confidence
        self.entry_price = entry_price
        self.stop_loss = stop_loss
        self.take_profit = take_profit
        self.reason = reason
        self.indicators_aligned = indicators_aligned
        self.strategy_used = strategy_used
        self.created_at = datetime.now()

    def to_dict(self):
        """Convert signal to dictionary for database storage"""
        return {
            'ticker': self.ticker,
            'timestamp': self.timestamp.isoformat(),
            'signal_type': self.signal_type,
            'confidence': self.confidence,
            'entry_price': self.entry_price,
            'stop_loss': self.stop_loss,
            'take_profit': self.take_profit,
            'reason': self.reason,
            'indicators': ','.join(self.indicators_aligned),
            'strategy': self.strategy_used,
            'risk_reward': round((self.take_profit - self.entry_price) / (self.entry_price - self.stop_loss),
                                 2) if self.stop_loss != self.entry_price else 0
        }

    def __repr__(self):
        return f"TradeSignal({self.signal_type}, {self.ticker}, {self.confidence:.0f}%, Risk:Reward {(self.take_profit - self.entry_price) / (self.entry_price - self.stop_loss):.2f}:1)"


