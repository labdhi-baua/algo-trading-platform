class MasterStrategy:
    """
    Complete Master Strategy Implementation
    Combines all indicators and strategies
    Optimized for 4-hour swing trading
    """

    def __init__(self, db_path: str = 'trading.db'):
        """Initialize strategy with optimized parameters"""

        self.db_path = db_path
        self.name = "Master Swing Trader - 4H Optimized"
        self.timeframe = "4H"
        self.version = "2.0 - Complete Implementation"

        # ===== TREND PARAMETERS =====
        self.ma_fast = 50  # SMA fast period
        self.ma_slow = 200  # SMA slow period

        # ===== MOMENTUM PARAMETERS =====
        self.rsi_period = 14
        self.rsi_buy_lower = 30  # Buy zone lower
        self.rsi_buy_upper = 45  # Buy zone upper
        self.rsi_sell_lower = 55  # Sell zone lower
        self.rsi_sell_upper = 70  # Sell zone upper

        self.macd_fast = 12
        self.macd_slow = 26
        self.macd_signal = 9

        self.stoch_k_period = 14
        self.stoch_k_smooth = 3
        self.stoch_d_smooth = 3
        self.stoch_oversold = 30
        self.stoch_overbought = 70

        self.cci_period = 20
        self.cci_overbought = 100
        self.cci_oversold = -100

        # ===== VOLATILITY PARAMETERS =====
        self.atr_period = 14
        self.atr_stop_multiple = 2.0  # Stop loss: 2 ATR
        self.atr_tp_multiple = 3.0  # Take profit: 3 ATR

        self.bb_period = 20
        self.bb_std_dev = 2.0

        # ===== TREND STRENGTH FILTER =====
        self.adx_period = 14
        self.adx_threshold = 25  # Minimum ADX for strong trend

        # ===== VOLUME FILTER =====
        self.volume_period = 20
        self.volume_ratio_min = 1.0  # Volume must be > average

        # ===== SUPPORT/RESISTANCE =====
        self.support_resistance_period = 20

        # ===== SIGNAL REQUIREMENTS (OPTIMIZED) =====
        self.min_buy_signals = 3  # Need 3+ buy signals
        self.min_buy_confidence = 65  # 65% minimum (increased from 50)
        self.min_sell_signals = 3  # Need 3+ sell signals (increased from 2)
        self.min_sell_confidence = 65  # 65% minimum (increased from 50)

        # ===== RISK MANAGEMENT =====
        self.risk_per_trade = 0.02  # 2% of account
        self.min_risk_reward = 1.5  # Minimum 1:1.5

        # Initialize database
        self._init_database()

        logger.info(f"✓ {self.name} initialized")
        logger.info(f"  Buy requirements: {self.min_buy_signals}+ signals, ≥{self.min_buy_confidence}% confidence")
        logger.info(f"  Sell requirements: {self.min_sell_signals}+ signals, ≥{self.min_sell_confidence}% confidence")

    def _init_database(self):
        """Create database tables if not exist"""
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()

        # Signals table
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS signals (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                ticker TEXT NOT NULL,
                timestamp DATETIME NOT NULL,
                signal_type TEXT,
                confidence REAL,
                entry_price REAL,
                stop_loss REAL,
                take_profit REAL,
                risk_reward REAL,
                reason TEXT,
                indicators TEXT,
                strategy TEXT,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                actioned INTEGER DEFAULT 0,
                UNIQUE(ticker, timestamp, signal_type)
            )
        ''')

        conn.commit()
        conn.close()

